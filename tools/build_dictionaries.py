#!/usr/bin/env python3
"""Builds the bundled word lists at app/src/main/assets/dict/{en,pt}.txt.

Sources (pinned to fixed revisions) are downloaded into tools/.cache/:

  English
    valid words  ENABLE2K word list ............................ public domain
                 SCOWL / Hunspell en_US ........................ SCOWL license (MIT-like)
    frequency    FrequencyWords en_50k (OpenSubtitles 2018) .... CC BY-SA 4.0
  Portuguese (Brazil)
    lexicon (headwords), corpus frequency (icf) and
    place-name / sensitive-word lists from fserb/pt-br ......... MIT
    VERO pt_BR Hunspell dictionary (LibreOffice) ............... LGPL 3 / MPL 2.0

Answer words ("common") must be frequent AND appear in a proofing dictionary
in lowercase, which drops names, acronyms and subtitle artifacts ("ain").

Portuguese only accepts dictionary headwords: singular nouns and adjectives
(masculine and feminine) and infinitive verbs. Plurals and conjugated forms
would multiply the words in every wheel (casa, casas, case, caso, casou...),
flooding the bonus jar and making grids feel repetitive.

Output format (UTF-8, read by Dictionary.kt):

  @lang <code>
  @common            one word per line, most common first (answer pool)
  @valid <n>         every valid n-letter word, sorted, concatenated in one line
  @display           "<plain> <accented>" pairs, sorted by plain form

Words are normalized to plain a-z (accents and cedilla removed) because the
letter wheel only has plain letters, like every Wordscapes-style game in PT.

Usage:  python tools/build_dictionaries.py [--cache DIR]
"""

from __future__ import annotations

import argparse
import re
import sys
import unicodedata
import urllib.request
import zipfile
from pathlib import Path

from hunspell import Hunspell

ROOT = Path(__file__).resolve().parent.parent
DATA = Path(__file__).resolve().parent / "data"
OUT = ROOT / "app" / "src" / "main" / "assets" / "dict"

MIN_LEN = 3
MAX_LEN = 7
COMMON_LIMIT = {"en": 20000, "pt": 22000}

GH = "https://raw.githubusercontent.com"
FSERB = f"{GH}/fserb/pt-br/93ba2a6f3b2f85262fba72df09d448c6bb2fa50a"
VERO = f"{GH}/LibreOffice/dictionaries/1e848fbddd7fd8e03fb696ecc03ee1068fab141c/pt_BR"
SOURCES = {
    "enable1.txt": f"{GH}/dolph/dictionary/233d25a56b9ac8bef906916ccf091a976995cce0/enable1.txt",
    "en_50k.txt": f"{GH}/hermitdave/FrequencyWords/525f9b560de45753a5ea01069454e72e9aa541c6/content/2018/en/en_50k.txt",
    "hunspell-en_US.zip": "https://github.com/en-wl/wordlist/releases/download/rel-2026.02.25/hunspell-en_US-2026.02.25.zip",
    "pt_lexico": f"{FSERB}/lexico",
    "pt_icf": f"{FSERB}/icf",
    "pt_paises": f"{FSERB}/listas/paises",
    "pt_estados": f"{FSERB}/listas/estados-br",
    "pt_continentes": f"{FSERB}/listas/continentes",
    "pt_negativas": f"{FSERB}/listas/negativas",
    "pt_BR.aff": f"{VERO}/pt_BR.aff",
    "pt_BR.dic": f"{VERO}/pt_BR.dic",
}

PLAIN = re.compile(r"[a-z]+")


def download(cache: Path, name: str) -> Path:
    path = cache / name
    if not path.exists():
        cache.mkdir(parents=True, exist_ok=True)
        print(f"  downloading {name} ...", file=sys.stderr)
        with urllib.request.urlopen(SOURCES[name]) as response:
            path.write_bytes(response.read())
    return path


def fetch(cache: Path, name: str) -> list[str]:
    return download(cache, name).read_text(encoding="utf-8").splitlines()


def lowercase_forms(aff: Path, dic: Path) -> set[str]:
    """Every word form of a Hunspell dictionary whose entry is all lowercase
    (proper nouns and acronyms are capitalized in Hunspell dictionaries)."""
    return Hunspell(aff, dic).forms(keep=lambda w: w.islower(), max_base_length=MAX_LEN + 3)


def read_list(name: str) -> list[str]:
    lines = (DATA / name).read_text(encoding="utf-8").splitlines()
    return [line.strip().lower() for line in lines if line.strip() and not line.startswith("#")]


def strip_accents(word: str) -> str:
    decomposed = unicodedata.normalize("NFD", word.lower())
    return "".join(c for c in decomposed if unicodedata.category(c) != "Mn")


def playable(word: str) -> bool:
    return MIN_LEN <= len(word) <= MAX_LEN and PLAIN.fullmatch(word) is not None


class Filter:
    """Exact words plus prefixes (a trailing '*' in the list files)."""

    def __init__(self, entries: list[str]):
        self.exact = {e for e in entries if not e.endswith("*")}
        self.prefixes = tuple(e[:-1] for e in entries if e.endswith("*"))

    def __contains__(self, word: str) -> bool:
        return word in self.exact or word.startswith(self.prefixes)


def write(lang: str, common: list[str], valid: set[str], display: dict[str, str]) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Wordlink dictionary - generated by tools/build_dictionaries.py, do not edit",
        f"@lang {lang}",
        "@common",
        *common,
    ]
    for n in range(MIN_LEN, MAX_LEN + 1):
        words = sorted(w for w in valid if len(w) == n)
        lines += [f"@valid {n}", "".join(words)]
    lines.append("@display")
    lines += [f"{plain} {shown}" for plain, shown in sorted(display.items())]
    (OUT / f"{lang}.txt").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{lang}: {len(common)} common, {len(valid)} valid, {len(display)} accented")


def build_en(cache: Path) -> None:
    blocked = Filter(read_list("blocklist_en.txt"))
    avoided = Filter(read_list("avoid_en.txt"))

    archive = download(cache, "hunspell-en_US.zip")
    unpacked = cache / "hunspell-en_US"
    if not (unpacked / "en_US.dic").exists():
        with zipfile.ZipFile(archive) as z:
            z.extractall(unpacked)
    proofing = lowercase_forms(unpacked / "en_US.aff", unpacked / "en_US.dic")

    enable = {l.strip() for l in fetch(cache, "enable1.txt")}
    valid = {w for w in enable | proofing if playable(w) and w not in blocked}

    common: list[str] = []
    seen: set[str] = set()
    for line in fetch(cache, "en_50k.txt"):
        word = line.split(" ")[0].strip()
        if word in valid and word in proofing and word not in seen and word not in avoided:
            seen.add(word)
            common.append(word)
            if len(common) == COMMON_LIMIT["en"]:
                break

    write("en", common, valid, {})


def pt_singulars(word: str) -> set[str]:
    """Singular candidates for a word that may be a plural."""
    out: set[str] = set()
    for plural, singular in (("ões", "ão"), ("ães", "ão"), ("ãos", "ão"), ("ais", "al"), ("éis", "el"),
                             ("óis", "ol"), ("uis", "ul"), ("is", "il"), ("ns", "m"), ("es", ""), ("s", "")):
        if word.endswith(plural):
            out.add(word[: len(word) - len(plural)] + singular)
    return out


def build_pt(cache: Path) -> None:
    blocked = Filter(read_list("blocklist_pt.txt"))
    avoided = Filter(
        read_list("avoid_pt.txt")
        + read_list("loanwords_pt.txt")
        + [strip_accents(w) for w in fetch(cache, "pt_negativas")]
    )
    for name in ("pt_paises", "pt_estados", "pt_continentes"):
        avoided.exact |= {strip_accents(w) for w in fetch(cache, name) if " " not in w.strip()}

    # The lexicon is mostly headwords, but still lists frequent plurals
    # ("anos", "coisas") and a few conjugated forms ("estou", "seja").
    entries = [w.strip().lower() for w in fetch(cache, "pt_lexico") if w.strip()]
    entry_set = set(entries)
    not_plural = set(read_list("not_plural_pt.txt"))
    verb_forms = Filter(read_list("verb_forms_pt.txt"))
    lexicon = [
        w for w in entries
        if strip_accents(w) not in verb_forms
        and (w in not_plural or not (w.endswith("s") and pt_singulars(w) & entry_set))
    ]
    proofing = lowercase_forms(download(cache, "pt_BR.aff"), download(cache, "pt_BR.dic"))
    proofing_plain = {strip_accents(w) for w in proofing}

    icf: list[str] = []
    for line in fetch(cache, "pt_icf"):
        form, _, score = line.partition(",")
        if form and score:
            icf.append(form.strip().lower())
    icf_rank = {form: i for i, form in reversed(list(enumerate(icf)))}

    # plain form -> every headword spelling that normalizes to it
    spellings: dict[str, set[str]] = {}
    for form in lexicon:
        plain = strip_accents(form)
        if playable(plain) and plain not in blocked:
            spellings.setdefault(plain, set()).add(form)
    valid = set(spellings)

    # Show the most frequent spelling: "acao" -> "ação", "esta" -> "está".
    display: dict[str, str] = {}
    for plain, forms in spellings.items():
        best = min(forms, key=lambda f: (icf_rank.get(f, len(icf)), f != plain, f))
        if best != plain:
            display[plain] = best

    common: list[str] = []
    seen: set[str] = set()
    for form in icf:
        plain = strip_accents(form)
        if plain in valid and plain in proofing_plain and plain not in seen and plain not in avoided:
            seen.add(plain)
            common.append(plain)
            if len(common) == COMMON_LIMIT["pt"]:
                break

    write("pt", common, valid, display)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--cache", type=Path, default=Path(__file__).resolve().parent / ".cache")
    args = parser.parse_args()
    build_en(args.cache)
    build_pt(args.cache)


if __name__ == "__main__":
    main()
