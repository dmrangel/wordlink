#!/usr/bin/env python3
"""Generates ui/icons/Lucide.kt from Lucide SVG icons (ISC License).

Modrinth's own icon set is built on Lucide, so using the same stroke icons
(24x24 grid, 2px round strokes) keeps the look consistent with the app.
Each icon becomes a lazily built Compose ImageVector; nothing is parsed
until the icon is first drawn.

Usage:  python tools/gen_icons.py [--source DIR]
"""

from __future__ import annotations

import argparse
import re
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "app" / "src" / "main" / "java" / "io" / "github" / "dmrangel" / "wordlink" / "ui" / "icons" / "Lucide.kt"
URL = "https://raw.githubusercontent.com/lucide-icons/lucide/main/icons/{}.svg"

ICONS = [
    "arrow-left", "book-open", "calendar-days", "check", "chevron-right", "circle", "coins", "flame",
    "hand", "house", "image", "languages", "lightbulb", "moon", "paintbrush", "palette", "pipette",
    "play", "plus", "rotate-ccw", "settings", "shuffle", "sparkles", "square", "squircle", "sun",
    "target", "trash", "trophy", "x", "zap-off",
]


def num(value: str | None) -> float:
    return float(value) if value else 0.0


def fmt(value: float) -> str:
    return f"{value:g}"


NUMBER = re.compile(r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?")


def normalize(d: str) -> str:
    """Re-tokenizes path data with explicit separators. SVG lets arc flags be
    written without spaces ("a2 2 0 0022 17"), which some parsers misread."""
    tokens: list[str] = []
    command, index, i = "", 0, 0
    while i < len(d):
        ch = d[i]
        if ch.isalpha():
            tokens.append(ch)
            command, index, i = ch.lower(), 0, i + 1
        elif ch in " ,\t\n":
            i += 1
        elif command == "a" and index % 7 in (3, 4):
            tokens.append(ch)
            index, i = index + 1, i + 1
        else:
            match = NUMBER.match(d, i)
            tokens.append(match.group(0))
            index, i = index + 1, match.end()
    return " ".join(tokens)


def element_path(el: ET.Element) -> str:
    tag = el.tag.split("}")[-1]
    a = el.attrib
    if tag == "path":
        return normalize(a["d"])
    if tag == "circle":
        cx, cy, r = num(a.get("cx")), num(a.get("cy")), num(a.get("r"))
        return f"M{fmt(cx - r)} {fmt(cy)}a{fmt(r)} {fmt(r)} 0 1 0 {fmt(2 * r)} 0a{fmt(r)} {fmt(r)} 0 1 0 {fmt(-2 * r)} 0"
    if tag == "rect":
        x, y, w, h = num(a.get("x")), num(a.get("y")), num(a["width"]), num(a["height"])
        rx = num(a.get("rx") or a.get("ry"))
        if rx == 0:
            return f"M{fmt(x)} {fmt(y)}h{fmt(w)}v{fmt(h)}h{fmt(-w)}z"
        return (
            f"M{fmt(x + rx)} {fmt(y)}h{fmt(w - 2 * rx)}a{fmt(rx)} {fmt(rx)} 0 0 1 {fmt(rx)} {fmt(rx)}"
            f"v{fmt(h - 2 * rx)}a{fmt(rx)} {fmt(rx)} 0 0 1 {fmt(-rx)} {fmt(rx)}h{fmt(-(w - 2 * rx))}"
            f"a{fmt(rx)} {fmt(rx)} 0 0 1 {fmt(-rx)} {fmt(-rx)}v{fmt(-(h - 2 * rx))}a{fmt(rx)} {fmt(rx)} 0 0 1 {fmt(rx)} {fmt(-rx)}z"
        )
    if tag == "line":
        return f"M{a['x1']} {a['y1']}L{a['x2']} {a['y2']}"
    if tag in ("polyline", "polygon"):
        points = a["points"].replace(",", " ").split()
        pairs = [f"{points[i]} {points[i + 1]}" for i in range(0, len(points), 2)]
        return "M" + "L".join(pairs) + ("z" if tag == "polygon" else "")
    raise ValueError(f"unsupported SVG element <{tag}>")


def kotlin_name(icon: str) -> str:
    return "".join(part.capitalize() for part in icon.split("-"))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", type=Path, default=Path(__file__).resolve().parent / ".cache" / "lucide")
    args = parser.parse_args()
    args.source.mkdir(parents=True, exist_ok=True)

    entries = []
    for icon in ICONS:
        svg = args.source / f"{icon}.svg"
        if not svg.exists():
            with urllib.request.urlopen(URL.format(icon)) as response:
                svg.write_bytes(response.read())
        paths = [element_path(el) for el in ET.parse(svg).getroot()]
        args_list = ",\n            ".join(f'"{p}"' for p in paths)
        name = kotlin_name(icon)
        entries.append(f"    val {name}: ImageVector by lazy {{\n        icon(\n            \"{name}\",\n            {args_list},\n        )\n    }}")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by tools/gen_icons.py from Lucide icons (https://lucide.dev, ISC License). Do not edit.\n"
        "package io.github.dmrangel.wordlink.ui.icons\n\n"
        "import androidx.compose.ui.graphics.Color\n"
        "import androidx.compose.ui.graphics.SolidColor\n"
        "import androidx.compose.ui.graphics.StrokeCap\n"
        "import androidx.compose.ui.graphics.StrokeJoin\n"
        "import androidx.compose.ui.graphics.vector.ImageVector\n"
        "import androidx.compose.ui.graphics.vector.addPathNodes\n"
        "import androidx.compose.ui.unit.dp\n\n"
        "object Lucide {\n"
        + "\n\n".join(entries)
        + "\n}\n\n"
        "private fun icon(name: String, vararg paths: String): ImageVector =\n"
        "    ImageVector.Builder(name, 24.dp, 24.dp, 24f, 24f).apply {\n"
        "        for (d in paths) {\n"
        "            addPath(\n"
        "                pathData = addPathNodes(d),\n"
        "                stroke = SolidColor(Color.Black),\n"
        "                strokeLineWidth = 2f,\n"
        "                strokeLineCap = StrokeCap.Round,\n"
        "                strokeLineJoin = StrokeJoin.Round,\n"
        "            )\n"
        "        }\n"
        "    }.build()\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"{OUT.relative_to(ROOT)}: {len(entries)} icons")


if __name__ == "__main__":
    main()
